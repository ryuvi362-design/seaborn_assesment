import numpy as np
import pandas as pd

np.random.seed(42)

# Create dataset
df_d = pd.DataFrame({
    'order_value': np.random.randint(100, 1000, 100),
    'delivery_time': np.random.randint(15, 60, 100),
    'distance': np.random.uniform(1, 20, 100),
    'rating': np.random.randint(1, 6, 100),
    'discount': np.random.randint(0, 31, 100),
    'city': np.random.choice(['Ahmedabad', 'Surat', 'Vadodara'], 100)
})

print(df_d.head())

import seaborn as sns
import matplotlib.pyplot as plt

# Create pairplot
sns.pairplot(df_d, hue='city')

# Save the pairplot
plt.savefig('section_d_pairplot.png', dpi=200)

plt.show()

# Create correlation heatmap
corr = df_d.select_dtypes(include='number').corr()

plt.figure(figsize=(8, 6))
sns.heatmap(corr, annot=True, cmap='coolwarm')

plt.title('Correlation Heatmap')
plt.tight_layout()

# Save the heatmap
plt.savefig('section_d_heatmap.png', dpi=200)

plt.show()

# Improved pairplot
plot = sns.pairplot(df_d, hue='city')
plot.fig.suptitle('Food Delivery Data Analysis', y=1.02)

plot.savefig('section_d_pairplot_improved.png', dpi=200)
plt.show()

