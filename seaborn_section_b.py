import numpy as np
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

np.random.seed(7)

# Create dataset
df = pd.DataFrame({
    'order_value': np.random.uniform(100, 800, 200),
    'distance_km': np.random.uniform(1, 20, 200),
    'delivery_time_mins': np.random.normal(30, 8, 200),
    'rating': np.random.uniform(1, 5, 200),
    'discount_pct': np.random.uniform(0, 30, 200)
})

# Add missing values
df.loc[np.random.choice(df.index, 10), 'delivery_time_mins'] = np.nan
df.loc[np.random.choice(df.index, 10), 'rating'] = np.nan

# Fill missing values with median
df['delivery_time_mins'] = df['delivery_time_mins'].fillna(
    df['delivery_time_mins'].median()
)
df['rating'] = df['rating'].fillna(df['rating'].median())

# Calculate delivery speed
df['delivery_speed_kmph'] = (
    df['distance_km'] / (df['delivery_time_mins'] / 60)
)

# Divide speed into three groups
df['speed_band'] = pd.qcut(
    df['delivery_speed_kmph'],
    q=3,
    labels=['Slow', 'Normal', 'Fast']
)

# Create correlation heatmap
plt.figure(figsize=(8, 6))
sns.heatmap(df.select_dtypes(include='number').corr(),
            annot=True, cmap='coolwarm')
plt.title('Correlation Heatmap')
plt.tight_layout()
plt.savefig('correlation_heatmap.png', dpi=150)
plt.show()

# Create pairplot
sns.pairplot(
    df,
    vars=['order_value', 'distance_km',
          'delivery_time_mins', 'rating'],
    hue='speed_band'
)
plt.savefig('pairplot.png', dpi=150)
plt.show()

