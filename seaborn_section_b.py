import pandas as pd
import numpy as np

np.random.seed(42)

# Create restaurant dataset
data = {
    'restaurant_name': np.random.choice(
        ['Food Hub', 'Pizza House', 'Burger Point',
         'Spice Garden', 'Tasty Bites'], 50
    ),
    'city': np.random.choice(
        ['Ahmedabad', 'Vadodara', 'Surat'], 50
    ),
    'order_value': np.random.randint(100, 1000, 50),
    'delivery_time_mins': np.random.randint(15, 50, 50),
    'rating': np.random.randint(1, 6, 50),
    'cuisine_type': np.random.choice(
        ['Indian', 'Chinese', 'Italian'], 50
    )
}

df = pd.DataFrame(data)

print("First 5 Rows:")
print(df.head())

# Calculate restaurant averages
result = df.groupby('restaurant_name').agg(
    mean_order_value=('order_value', 'mean'),
    mean_delivery_time=('delivery_time_mins', 'mean'),
    mean_rating=('rating', 'mean')
)

# Filter restaurants
result = result[
    (result['mean_rating'] > 4) &
    (result['mean_delivery_time'] < 35)
]

# Sort by average order value
result = result.sort_values(
    by='mean_order_value', ascending=False
)

# Reset the index
result = result.reset_index()

print("\nRestaurant Performance Report:")
print(result)

